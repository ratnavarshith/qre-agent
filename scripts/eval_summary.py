"""Compare the models of the full eval: writes results/eval/summary.md from each model's
runs.jsonl (grader v1, as graded when the runs ran), runs-v2.jsonl (grader v2, from
run_eval.py --regrade), runs-first-attempt.jsonl (the runs before any rerun) and meta.json.
Appends results/eval/notes.md and results/eval/failure-review.md (written by hand).

  .venv/Scripts/python scripts/eval_summary.py
"""

import json
import statistics
from collections import Counter, defaultdict

from qre_agent.eval import CATEGORIES, DIFFICULTIES, TYPES, _rates, _spread, api_error_counts
from qre_agent.spend import REPO_ROOT

EVAL_DIR = REPO_ROOT / "results" / "eval"
RUNS = {  # short name -> results directory of the full eval
    "gemini-2.5-flash": "google_gemini-2.5-flash/2026-10-09",
    "deepseek-v3.2": "deepseek_deepseek-v3.2/2026-10-09",
    "haiku-4.5": "anthropic_claude-haiku-4.5/2026-10-09",
    "sonnet-5": "anthropic_claude-sonnet-5/2026-10-09",
}
# Why a run's grade changed from v1 to v2, by the v1 failure reason that v2 no longer gives.
RULES = [
    ("unitary is not the QFT", "QFT in either qubit order"),
    ("verify numbers_match", "verifier: float noise, written-out units"),
    ("verify fields_match", "verifier: float noise, written-out units"),
    ("doesn't say it assumed anything", "a stated value is the assumption"),
]
NON_ASCII = "non-ASCII build_circuit bug"
V2_RULES = """\
Rules (each with a test; see the grader v2 commits on `semantics.py`, `verify.py` and `eval.py`):

- **QFT in either qubit order.** The QFT written with qubit 0 as the most significant bit is \
the same circuit with its qubits relabelled; v1 took only Qiskit's order.
- **Verifier: float noise, written-out units.** A value copied with digits past a double's \
precision matches (relative 1e-12), and "seconds", "milliseconds" and so on convert like "s" \
and "ms". This is the agent's verify tool too.
- **A stated value is the assumption.** An ambiguous task's answer that states the value it \
used passes without the word "assumed" or "default".
- **No-answer labels.** Answer JSON with no estimate behind it is made-up numbers, not \
unit/format; a reply asking the user for a value is gave up."""


def jsonl(path):
    return (
        [json.loads(line) for line in path.read_text("utf-8").splitlines()] if path.exists() else []
    )


def load(path):
    meta = json.loads((path / "meta.json").read_text(encoding="utf-8"))
    return (
        jsonl(path / "runs.jsonl"),
        jsonl(path / "runs-v2.jsonl"),
        jsonl(path / "runs-first-attempt.jsonl"),
        meta,
    )


def graded(records):
    return [r for r in records if r["category"] != "api error"]


def rate(records, key):
    return _spread(_rates(records, key))


def percentile(values, q):
    """Linear interpolation between the closest ranks (the 'inclusive' method)."""
    return statistics.quantiles(values, n=100, method="inclusive")[q - 1]


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join(map(str, row)) + " |" for row in rows]


def why_changed(v1, v2):
    """The rule behind a run graded differently by v1 and v2, or 'other' (which would mean the
    regrade doesn't reproduce the run, not a rule)."""
    if v1["category"] == "unit/format" and v2["category"] in ("made-up numbers", "gave up"):
        return f"no-answer label: {v2['category']}"
    gone = [f["reason"] for f in v1["failures"] if f not in v2["failures"]]
    rules = {name for text, name in RULES for reason in gone if text in reason}
    return " + ".join(sorted(rules)) or "other"


def main():
    data = {name: load(EVAL_DIR / path) for name, path in RUNS.items()}
    names = list(data)
    v1 = {n: d[0] for n, d in data.items()}
    v2 = {n: d[1] for n, d in data.items()}
    meta0 = next(iter(data.values()))[3]
    lines = [
        "# Eval: four models on 40 tasks x 3 runs",
        "",
        (
            "Generated by `scripts/eval_summary.py`. Tasks: `evals/tasks.yaml` (sha256 "
            f"{meta0['tasks_sha256'][:12]}): 25 standard, 10 free-form, 5 ambiguous. Each task ran "
            "3 times per model (seeds 0, 1, 2; providers may ignore the seed). A run is correct "
            "when the task's checks and the final verify pass (`docs/agent-design.md`, Evals). "
            "Rates are mean ± sample standard deviation across the 3 passes over the tasks, with "
            "(min–max): run-to-run noise, not a confidence interval. Api-error runs are left "
            "out of the rates."
        ),
        "",
        (
            "**Two graders.** v1 graded the runs as they ran. v2 fixes grader problems found by "
            "reading the failures (listed under *What changed from v1 to v2*) and regraded every "
            "stored run from its trace with no LLM calls. The headline uses v2; v1 is shown next "
            "to it. Separately, 27 runs hit a harness bug (non-ASCII code crashed `build_circuit`) "
            "and were rerun after the fix; both graders see the rerun, and the runs before the fix "
            "are compared under *Non-ASCII bug: the 27 rerun runs*."
        ),
        "",
        "## Headline (grader v2)",
        "",
    ]
    rows = []
    for n in names:
        rs1, rs2, runs = graded(v1[n]), graded(v2[n]), v2[n]
        lat = [r["latency_s"] for r in runs]
        rows.append([
            n, rate(rs2, lambda r: r["correct"]), rate(rs1, lambda r: r["correct"]),
            rate(rs2, lambda r: r["verify_first_try"]),
            f"${statistics.mean(r['cost_usd'] for r in runs):.4f}",
            f"{statistics.median(lat):.0f} s", f"{percentile(lat, 95):.0f} s",
        ])  # fmt: skip
    lines += table(["model", "correct (v2)", "correct (v1)", "verify first try (v2)",
                    "cost per run", "latency p50", "p95"], rows)  # fmt: skip
    lines += ["", "## Setup", ""]
    rows = []
    for n in names:
        rs, _, _, meta = data[n]
        cfg, git = meta["config"], meta.get("git") or {}
        first, left = api_error_counts(rs)
        reruns = [e for e in meta.get("reruns", []) if isinstance(e, dict) and e.get("reason")]
        rows.append([
            n, len(rs), (git.get("commit") or "?")[:7],
            f"{cfg['max_rpm']} rpm" if cfg.get("max_rpm") else "no",
            "yes" if cfg.get("cache") else "implicit" if n.startswith(("gemini", "deepseek")) else "no",
            f"{first} / {left}",
            ", ".join(f"{len(e['runs'])} ({e['reason'].split(',')[0]}, {e['git']['commit'][:7]})"
                      for e in reruns) or "-",
        ])  # fmt: skip
    lines += table(["model", "runs", "commit", "paced", "prompt cache",
                    "api errors: first try / after rerun", "reruns"], rows)  # fmt: skip
    lines += [
        "",
        (
            "Versions (all models): "
            + ", ".join(f"{k} {v}" for k, v in meta0["versions"].items())
            + f". Hardware: {meta0['hardware']['processor']}, {meta0['hardware']['platform']}, "
            f"Python {meta0['hardware']['python']}. At most {meta0['config']['max_steps']} LLM "
            f"calls per run, {meta0['config']['max_tokens']} tokens per call. No retries."
        ),
        "",
        "## Correct rate, v2 and v1",
        "",
    ]

    def by_group(groups):
        rows = []
        for label, pick in groups:
            row = [label]
            for n in names:
                for rs in (v2[n], v1[n]):
                    row.append(rate([r for r in graded(rs) if pick(r)], lambda r: r["correct"]))
            rows.append(row)
        return table(["", *[f"{n} {v}" for n in names for v in ("v2", "v1")]], rows)

    lines += by_group([("all 40 tasks", lambda r: True)])
    lines += ["", "By type:", ""]
    lines += by_group([(t, lambda r, t=t: r["type"] == t) for t in TYPES])
    lines += ["", "By difficulty (the ambiguous tasks are their own difficulty and type):", ""]
    lines += by_group([(d, lambda r, d=d: r["difficulty"] == d) for d in DIFFICULTIES])

    lines += [
        "",
        "## Verify",
        "",
        (
            "Passed the deterministic verifier on the first try, only after the one retry, or "
            "never (v2; v1 in brackets). Verify passing is not the same as correct: it checks "
            "the answer against the tool outputs, not that the circuit or settings are right."
        ),
        "",
    ]
    rows = []
    for n in names:
        a, b = graded(v2[n]), graded(v1[n])
        row = [n]
        for key in (
            lambda r: r["verify_first_try"],
            lambda r: r["verify_after_retry"],
            lambda r: not (r["verify_first_try"] or r["verify_after_retry"]),
        ):
            row.append(f"{rate(a, key)} [{rate(b, key)}]")
        row.append(rate(a, lambda r: r["correct"]))
        rows.append(row)
    lines += table(["model", "first try", "only after the retry", "never", "correct"], rows)

    lines += ["", "## Failures by category", "", "Failed runs out of 120 per model, v2 (v1).", ""]
    c1 = {n: Counter(r["category"] for r in v1[n] if r["category"]) for n in names}
    c2 = {n: Counter(r["category"] for r in v2[n] if r["category"]) for n in names}
    rows = [
        [c, *[f"{c2[n][c]} ({c1[n][c]})" if c1[n][c] or c2[n][c] else "" for n in names]]
        for c in CATEGORIES
        if any(c1[n][c] or c2[n][c] for n in names)
    ]
    rows.append(["**all failed runs**",
                 *[f"{sum(c2[n].values())} ({sum(c1[n].values())})" for n in names]])  # fmt: skip
    lines += table(["category", *names], rows)

    lines += ["", "## What changed from v1 to v2", ""]
    changes = {n: [(a, b, why_changed(a, b)) for a, b in zip(v1[n], v2[n], strict=True)
                   if (a["correct"], a["category"]) != (b["correct"], b["category"])]
               for n in names}  # fmt: skip
    flips = {n: sum(a["verify_first_try"] != b["verify_first_try"]
                    for a, b in zip(v1[n], v2[n], strict=True)) for n in names}  # fmt: skip
    reasons = sorted({why for n in names for _, _, why in changes[n]})
    lines += V2_RULES.splitlines() + ["", "Runs graded differently, by rule:", ""]
    lines += table(
        ["rule", *names],
        [[why, *[sum(w == why for *_, w in changes[n]) or "" for n in names]] for why in reasons]
        + [["verify first-try flag changed", *[flips[n] or "" for n in names]]],
    )
    lines += ["", "Every run graded differently:", ""]
    lines += table(
        ["model", "task", "run", "v1", "v2", "rule"],
        [[n, a["task"], a["repeat"], a["category"] or "correct", b["category"] or "correct", why]
         for n in names for a, b, why in changes[n]],
    )  # fmt: skip

    lines += [
        "",
        "## Non-ASCII bug: the 27 rerun runs",
        "",
        (
            "`build_circuit` piped the agent's code to the sandbox in the Windows code page, so a "
            "π or ⟩ in the code raised UnicodeEncodeError before anything ran. Fixed in 8e394d1; "
            "the runs that hit it were rerun once with the same seed. Runs that never wrote "
            "non-ASCII code can't be affected by the fix, so the rest stand. Before = the "
            "original run, after = the rerun; both graded v1 and v2."
        ),
        "",
    ]
    rows, totals = [], defaultdict(lambda: [0, 0, 0, 0, 0])
    for n in names:
        first = {(r["task"], r["repeat"]): r for r in data[n][2]}
        after2 = {(r["task"], r["repeat"]): r for r in v2[n]}
        for r in v1[n]:
            if NON_ASCII not in (r.get("rerun_of") or {}).get("reason", ""):
                continue
            key = (r["task"], r["repeat"])
            before = first[key]
            rows.append([n, r["task"], r["repeat"], before["category"] or "correct",
                         r["category"] or "correct", after2[key]["category"] or "correct",
                         before["tool_errors"], r["tool_errors"]])  # fmt: skip
            t = totals[n]
            t[0] += 1
            t[1] += before["correct"]
            t[2] += r["correct"]
            t[3] += after2[key]["correct"]
            t[4] += r["cost_usd"]
    lines += table(["model", "runs rerun", "correct before (v1)", "correct after (v1)",
                    "correct after (v2)", "rerun cost"],
                   [[n, t[0], t[1], t[2], t[3], f"${t[4]:.2f}"] for n, t in totals.items()])  # fmt: skip
    lines += [""]
    lines += table(["model", "task", "run", "before (v1)", "after (v1)", "after (v2)",
                    "tool errors before", "after"], rows)  # fmt: skip

    lines += [
        "",
        "## Cost",
        "",
        (
            "Per run = one task, one attempt, all its LLM calls. `ours` prices tokens from "
            "`budgets.yaml` (conservative); `billed` is what OpenRouter reported. The 120 stored "
            "runs per model, reruns included; the replaced first attempts are in the eval's "
            "spend but not here."
        ),
        "",
    ]
    rows = []
    for n in names:
        rs = v2[n]
        ours, billed = sum(r["cost_usd"] for r in rs), sum(r["reported_cost_usd"] or 0 for r in rs)
        per = [r["cost_usd"] for r in rs]
        rows.append([
            n, f"${ours:.2f}", f"${billed:.2f}", f"{100 * (billed / ours - 1):+.0f}%",
            f"${statistics.mean(per):.4f} ± {statistics.stdev(per):.4f}",
            f"{sum(r['input_tokens'] for r in rs) / len(rs):,.0f}",
            f"{100 * sum(r['cached_tokens'] for r in rs) / sum(r['input_tokens'] for r in rs):.0f}%",
            f"{sum(r['output_tokens'] for r in rs) / len(rs):,.0f}",
        ])  # fmt: skip
    lines += table(["model", "total ours", "total billed", "billed vs ours",
                    "per run (ours), mean ± sd", "input tokens/run", "of which cached",
                    "output tokens/run"], rows)  # fmt: skip

    lines += [
        "",
        "## Steps and latency",
        "",
        (
            "Steps = LLM calls per run. Latency = wall time of a run (LLM calls plus tools), with "
            "the request pacer's waiting left out. p95 by linear interpolation over the 120 runs."
        ),
        "",
    ]
    rows = []
    for n in names:
        rs = v2[n]
        lat, steps = [r["latency_s"] for r in rs], [r["steps"] for r in rs]
        rows.append([
            n, f"{statistics.mean(steps):.1f} ± {statistics.stdev(steps):.1f}",
            f"{statistics.mean(r['tool_errors'] for r in rs):.2f}",
            f"{statistics.median(lat):.0f} s", f"{percentile(lat, 95):.0f} s", f"{max(lat):.0f} s",
            f"{sum(lat) / 60:.0f} min",
        ])  # fmt: skip
    lines += table(["model", "steps", "tool errors/run", "latency p50", "p95", "max",
                    "total run time"], rows)  # fmt: skip

    lines += [
        "",
        "## Per task (v2)",
        "",
        "Correct runs out of 3; v1 in brackets where it differs.",
        "",
    ]
    by_task = {n: defaultdict(lambda: [[], []]) for n in names}
    for n in names:
        for i, rs in enumerate((v2[n], v1[n])):
            for r in rs:
                by_task[n][r["task"]][i].append(r)
    rows = []
    for task, (rs0, _) in by_task[names[0]].items():
        row = [task, rs0[0]["type"], rs0[0]["difficulty"]]
        for n in names:
            new, old = (sum(r["correct"] for r in rs) for rs in by_task[n][task])
            api = any(r["category"] == "api error" for r in by_task[n][task][0])
            row.append(
                f"{new}/3" + (f" [{old}]" if old != new else "") + (" (api error)" if api else "")
            )
        rows.append(row)
    lines += table(["task", "type", "difficulty", *names], rows)

    for extra in ("notes.md", "failure-review.md"):  # written by hand after reading the results
        if (EVAL_DIR / extra).exists():
            lines += ["", (EVAL_DIR / extra).read_text(encoding="utf-8").rstrip(), ""]
    (EVAL_DIR / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {EVAL_DIR / 'summary.md'}")


if __name__ == "__main__":
    main()
